function pad(x){return x<10?"0"+x:""+x;}
function fmtWhen(ts){
  var d=new Date(ts),now=new Date(),t=pad(d.getHours())+":"+pad(d.getMinutes());
  var tm=new Date(now.getFullYear(),now.getMonth(),now.getDate()+1);
  if(d.toDateString()===now.toDateString())return "бүгүн саат "+t;
  if(d.toDateString()===tm.toDateString())return "эртең саат "+t;
  return pad(d.getDate())+"."+pad(d.getMonth()+1)+" күнү саат "+t;
}
function fmtRem(ms){
  var m=Math.max(1,Math.ceil(ms/60000)),h=Math.floor(m/60);m=m%60;
  return h>0?(h+" саат "+m+" мүнөт"):(m+" мүнөт");
}

