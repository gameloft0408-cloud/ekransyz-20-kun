var sos=$("#sos"),step=0,breathTimer=null;
var stepsEls=$$("#sos .step"),stepNav=$$("#sos-steps li");
function stopBreath(){clearTimeout(breathTimer);$("#breath").classList.remove("run");}
function startBreath(){
  stopBreath();
  var b=$("#breath"),lab=$("#breath-label"),inhale=true;
  void b.offsetWidth;b.classList.add("run");
  (function loop(){
    lab.textContent=inhale?"Дем алыңыз":"Акырын чыгарыңыз";
    breathTimer=setTimeout(function(){inhale=!inhale;loop();},inhale?4000:6000);
  })();
}
function showStep(i){
  step=Math.max(0,Math.min(2,i));
  stepsEls.forEach(function(s,k){s.hidden=k!==step;});
  stepNav.forEach(function(li,k){if(k===step)li.setAttribute("aria-current","step");else li.removeAttribute("aria-current");});
  $("#sos-prev").hidden=step===0;
  $("#sos-next").textContent=step===2?"Тынчтандым, жабуу":"Кийинки кадам";
  if(step===0)startBreath();else stopBreath();
}
function openSos(){if(!sos.open){if(sos.showModal)sos.showModal();else sos.setAttribute("open","");}showStep(0);}
function closeSos(){stopBreath();if(sos.close)sos.close();else sos.removeAttribute("open");}
document.addEventListener("click",function(e){var b=e.target.closest&&e.target.closest("[data-open-sos]");if(b)openSos();});
$("#sos-close").addEventListener("click",closeSos);
$("#sos-prev").addEventListener("click",function(){showStep(step-1);});
$("#sos-next").addEventListener("click",function(){if(step===2)closeSos();else showStep(step+1);});
sos.addEventListener("click",function(e){if(e.target===sos)closeSos();});
sos.addEventListener("close",stopBreath);

